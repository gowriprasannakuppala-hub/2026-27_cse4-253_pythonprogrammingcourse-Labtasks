# Create a list
my_list = [40, 10, 30, 20]

print("Original List:", my_list)

# Insert an element
my_list.insert(1, 50)
print("After Insert:", my_list)

# Append an element
my_list.append(60)
print("After Append:", my_list)

# Remove an element
my_list.remove(30)
print("After Remove:", my_list)

# Sort the list
my_list.sort()
print("After Sort:", my_list)

# Reverse the list
my_list.reverse()
print("After Reverse:", my_list)