# String creation
str1 = "Hello"
str2 = "Python"

print("String 1:", str1)
print("String 2:", str2)

# Concatenation
result = str1 + " " + str2
print("Concatenation:", result)

# Repetition
print("Repetition:", str1 * 3)

# Slicing
print("Slicing:", str2[0:3])
print("Reverse:", str2[::-1])